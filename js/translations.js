// Translation Manager
class TranslationManager {
    constructor() {
        this.currentLanguage = localStorage.getItem('siteLang') || 'en';
    }
    
    setLanguage(lang) {
        this.currentLanguage = lang;
        localStorage.setItem('siteLang', lang);
        this.updatePageContent();
    }
    
    getLanguage() {
        return this.currentLanguage;
    }
    
    translate(page, key) {
        const keys = key.split(/[:.]/).filter(k => k); // Split by both : and . for nested access
        let value = translations[this.currentLanguage]?.[page];
        
        for (const k of keys) {
            // Handle array indices (numeric keys)
            if (/^\d+$/.test(k)) {
                value = value?.[parseInt(k)];
            } else {
                value = value?.[k];
            }
        }
        
        return value || key;
    }
    
    updatePageContent() {
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const [page, ...keyParts] = key.split(':');
            const translationKey = keyParts.join(':');
            const text = this.translate(page, translationKey);
            
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = text;
            } else {
                element.textContent = text;
            }
        });
        
        document.querySelectorAll('[data-i18n-html]').forEach(element => {
            const key = element.getAttribute('data-i18n-html');
            const [page, ...keyParts] = key.split(':');
            const translationKey = keyParts.join(':');
            const text = this.translate(page, translationKey);
            element.innerHTML = text;
        });
    }
}

